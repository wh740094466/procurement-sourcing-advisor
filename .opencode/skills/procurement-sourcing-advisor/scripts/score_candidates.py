VALID_METHODS = {"minmax", "thresholds", "boolean", "presence", "categorical", "keyword", "manual", "reviews"}
VALID_OPS = {
    "lte",
    "gte",
    "lt",
    "gt",
    "eq",
    "neq",
    "in",
    "not_in",
    "contains_any",
    "contains_all",
    "not_contains_any",
    "exists",
    "truthy",
    "matches",
}
VALID_MISSING = {"worst", "neutral", "zero", "review"}


def validate_scorecard(scorecard: dict[str, Any]) -> tuple[list[str], list[str]]:
    errors: list[str] = []
    warnings: list[str] = []
    dimensions = scorecard.get("dimensions")
    if not isinstance(dimensions, list) or not dimensions:
        errors.append("scorecard.dimensions must be a non-empty array")
        return errors, warnings

    ids: set[str] = set()
    total_weight = 0.0
    for index, dim in enumerate(dimensions):
        if not isinstance(dim, dict):
            errors.append(f"dimensions[{index}] must be an object")
            continue
        dim_id = normalize_text(dim.get("id"))
        if not dim_id:
            errors.append(f"dimensions[{index}].id is required")
        elif dim_id in ids:
            errors.append(f"duplicate dimension id: {dim_id}")
        ids.add(dim_id)
        try:
            weight = float(dim.get("weight", 0))
        except (TypeError, ValueError):
            weight = 0
        if weight <= 0:
            errors.append(f"dimension {dim_id or index} weight must be > 0")
        total_weight += max(0.0, weight)
        method = dim.get("method")
        if method not in VALID_METHODS:
            errors.append(f"dimension {dim_id or index} has unknown method {method!r}")
        if method != "manual" and not dim.get("field"):
            errors.append(f"dimension {dim_id or index} requires field")
        if method == "minmax" and dim.get("direction") not in {"higher_better", "lower_better"}:
            errors.append(f"dimension {dim_id or index} minmax requires direction")
        if method == "thresholds" and not isinstance(dim.get("thresholds"), list):
            errors.append(f"dimension {dim_id or index} thresholds requires a list")
        if method == "categorical" and not isinstance(dim.get("map"), dict):
            errors.append(f"dimension {dim_id or index} categorical requires map")
        if method == "keyword" and not isinstance(dim.get("rules"), list):
            errors.append(f"dimension {dim_id or index} keyword requires rules")
        if dim.get("missing", "worst") not in VALID_MISSING:
            errors.append(f"dimension {dim_id or index} has invalid missing policy")
        if method == "manual" and not dim.get("evidence_required", True):
            warnings.append(f"manual dimension {dim_id or index} does not require evidence; this weakens auditability")

    staged = bool(scorecard.get("stages"))
    if staged:
        group_totals: dict[str, float] = {}
        for dim in dimensions:
            if not isinstance(dim, dict):
                continue
            group = dim.get("group")
            if group not in {"fit", "value", "risk"}:
                errors.append(f"dimension {dim.get('id')} requires group fit/value/risk in staged mode")
                continue
            group_totals[group] = group_totals.get(group, 0.0) + float(dim.get("weight", 0) or 0)
        for group, total in group_totals.items():
            if total and abs(total - 1.0) > 1e-6:
                errors.append(f"{group} group weights must sum to 1.0 (got {total:.6f})")
        if "value" not in group_totals:
            errors.append("staged scorecard requires at least one value dimension")
    elif abs(total_weight - 1.0) > 1e-6:
        errors.append(f"dimension weights must sum to 1.0 (got {total_weight:.6f})")

    filters = scorecard.get("hard_filters", [])
    if not isinstance(filters, list):
        errors.append("scorecard.hard_filters must be an array")
    else:
        for index, flt in enumerate(filters):
            if not isinstance(flt, dict):
                errors.append(f"hard_filters[{index}] must be an object")
                continue
            if not flt.get("field"):
                errors.append(f"hard_filters[{index}].field is required")
            if flt.get("op") not in VALID_OPS:
                errors.append(f"hard_filters[{index}] has unknown op {flt.get('op')!r}")
            if flt.get("missing", "review") not in {"fail", "pass", "review"}:
                errors.append(f"hard_filters[{index}] has invalid missing policy")
    return errors, warnings


def _expected(flt: dict[str, Any], brief: dict[str, Any]) -> Any:
    if "value_from" in flt:
        path = flt.get("value_from")
        value = get_path(brief, path)
        if value is None and isinstance(path, str):
            value = brief.get(path)
        return value
    value = flt.get("value")
    if isinstance(value, dict) and "from_brief" in value:
        return get_path(brief, value["from_brief"])
    return value


def _as_number(value: Any) -> float | None:
    if isinstance(value, bool):
        return None
    return parse_number(value)


def _compare(actual: Any, op: str, expected: Any) -> bool:
    if op in {"lte", "gte", "lt", "gt"}:
        left, right = _as_number(actual), _as_number(expected)
        if left is None or right is None:
            return False
        return {
            "lte": left <= right,
            "gte": left >= right,
            "lt": left < right,
            "gt": left > right,
        }[op]
    if op in {"eq", "neq"}:
        left, right = _as_number(actual), _as_number(expected)
        if left is not None and right is not None:
            equal = abs(left - right) < 1e-9
        else:
            equal = normalize_text(actual).lower() == normalize_text(expected).lower()
        return equal if op == "eq" else not equal
    if op in {"in", "not_in"}:
        values = expected if isinstance(expected, list) else [expected]
        normalized = {normalize_text(item).lower() for item in values}
        found = normalize_text(actual).lower() in normalized
        return found if op == "in" else not found
    if op in {"contains_any", "contains_all", "not_contains_any"}:
        values = expected if isinstance(expected, list) else [expected]
        text = normalize_text(actual).lower()
        hits = [normalize_text(item).lower() in text for item in values if not is_missing(item)]
        if op == "contains_any":
            return any(hits)
        if op == "contains_all":
            return bool(hits) and all(hits)
        return not any(hits)
    if op == "exists":
        exists = not is_missing(actual)
        return exists if bool(expected) else not exists
    if op == "truthy":
        return bool(actual)
    if op == "matches":
        try:
            return bool(re.search(str(expected), normalize_text(actual), re.IGNORECASE))
        except re.error:
            return False
    return False


def apply_hard_filters(
    candidate: dict[str, Any], filters: list[dict[str, Any]], brief: dict[str, Any]
) -> tuple[bool, bool, list[dict[str, Any]]]:
    eligible = True
    needs_review = False
    results: list[dict[str, Any]] = []
    for flt in filters:
        field = flt.get("field")
        actual = get_path(candidate, field)
        expected = _expected(flt, brief)
        missing_policy = flt.get("missing", "review")
        if is_missing(actual):
            if missing_policy == "fail":
                eligible = False
                status = "fail"
            elif missing_policy == "pass":
                status = "pass"
            else:
                status = "review"
                needs_review = True
            results.append(
                {
                    "filter_id": flt.get("id"),
                    "label": flt.get("label") or flt.get("id") or field,
                    "status": status,
                    "passed": status != "fail",
                    "actual": actual,
                    "expected": expected,
                    "reason": flt.get("missing_reason") or f"{field} 缺失，按 {missing_policy} 处理",
                }
            )
            continue
        if expected is None:
            status = "review"
            needs_review = True
            passed = True
            reason = flt.get("missing_reason") or "筛选阈值未提供，需人工确认"
        else:
            passed = _compare(actual, flt.get("op", "eq"), expected)
            status = "pass" if passed else "fail"
            reason = flt.get("reason") or f"{field} {flt.get('op')} {expected}"
            if not passed:
                # A static reason such as "尺寸未确认时需人工复核" is wrong when
                # the value is present and simply out of range.  Always show the
                # concrete comparison that eliminated the candidate.
                if any(token in reason for token in ("未确认", "未写", "缺失", "需人工")):
                    reason = f"{flt.get('label') or field} 不满足要求"
                reason = (
                    f"{reason}（实际值 {str(actual)[:60]}，要求 {flt.get('op')} "
                    f"{str(expected)[:60]}）"
                )
        if not passed:
            eligible = False
        results.append(
            {
                "filter_id": flt.get("id"),
                "label": flt.get("label") or flt.get("id") or field,
                "status": status,
                "passed": passed,
                "actual": actual,
                "expected": expected,
                "reason": reason,
            }
        )
    return eligible, needs_review, results


def _condition_verified(candidate: dict[str, Any]) -> bool:
    """A cheap price is only credible with a proven condition and invoice."""

    condition = normalize_text((candidate.get("attributes") or {}).get("condition"))
    invoice = normalize_text((candidate.get("detail") or {}).get("invoice"))
    return condition in {"全新", "全新原封"} and "发票" in invoice


def _manual_score(candidate: dict[str, Any], dim: dict[str, Any]) -> tuple[float | None, Any, str, bool]:
    dim_id = dim.get("id")
    manual = (candidate.get("manual_scores") or {}).get(dim_id)
    if not isinstance(manual, dict):
        return None, None, "", False
    score = _as_number(manual.get("score"))
    evidence = normalize_text(manual.get("evidence"))
    if score is None:
        return None, manual.get("score"), evidence, False
    if dim.get("evidence_required", True) and not evidence:
        return None, score, "", False
    return max(0.0, min(5.0, score)), score, evidence, True


def _score_dimension(
    candidate: dict[str, Any],
    dim: dict[str, Any],
    minmax_stats: dict[str, tuple[float, float]],
) -> tuple[float | None, Any, bool, str]:
    method = dim.get("method")
    if method == "manual":
        score, raw, evidence, known = _manual_score(candidate, dim)
        return score, raw, known, evidence

    if method == "reviews":
        # JD shows a positive rate rather than a 5-star rating, so the field
        # path (reviews.rating) may legitimately be null while the aggregate
        # evidence is still usable.
        reviews = candidate.get("reviews") or {}
        if reviews.get("status") != "ok":
            return None, None, False, ""
        rating = _as_number(reviews.get("rating"))
        positive_rate = _as_number(reviews.get("positive_rate"))
        if rating is not None:
            thresholds = dim.get("rating_thresholds") or [[4.7, 5], [4.5, 4], [4.2, 3], [4.0, 2]]
            raw = rating
        elif positive_rate is not None:
            thresholds = dim.get("positive_rate_thresholds") or [[99, 5], [98, 4.5], [95, 3.5], [90, 2]]
            raw = positive_rate
        else:
            return None, None, False, ""
        score = 1.0
        for threshold, value in sorted(thresholds, key=lambda pair: -float(pair[0])):
            if raw >= float(threshold):
                score = float(value)
                break
        # A single "100% positive" review is not stronger evidence than two
        # million reviews at 99%.  Pull small samples toward neutral so review
        # count cannot dominate the ranking.
        count = _as_number(reviews.get("rating_count"))
        if count is not None:
            factor = min(1.0, max(0.0, math.log10(max(count, 1)) / 2.0))
        else:
            factor = 0.5
        score = 2.5 + (score - 2.5) * factor
        negative_rate = _as_number(reviews.get("negative_rate"))
        if negative_rate is not None:
            score -= float(dim.get("negative_rate_penalty", 2.0)) * negative_rate
        score = max(0.0, min(5.0, score))
        note = (
            f"评分 {rating}，好评率 {positive_rate}，评价数 {reviews.get('rating_count')}，"
            f"样本 {reviews.get('sample_size')}，负评率 {negative_rate}"
        )
        return score, raw, True, note

    field = dim.get("field")
    actual = get_path(candidate, field)
    if is_missing(actual):
        return None, actual, False, ""

    if method == "presence":
        return 5.0, actual, True, f"{field} 有可用证据"

    if method == "boolean":
        mapping = dim.get("map") or {}
        key = normalize_text(actual).lower()
        if isinstance(actual, bool):
            key = "true" if actual else "false"
        if key in mapping:
            return max(0.0, min(5.0, float(mapping[key]))), actual, True, f"{field}={actual}"
        truthy = bool(actual) and normalize_text(actual).lower() not in {"false", "0", "no", "否", "不支持"}
        return (5.0 if truthy else 0.0), actual, True, f"{field}={actual}"

    if method == "categorical":
        mapping = dim.get("map") or {}
        key = normalize_text(actual).lower()
        for candidate_key, score in mapping.items():
            if normalize_text(candidate_key).lower() == key:
                return max(0.0, min(5.0, float(score))), actual, True, f"{field}={actual}"
        default = dim.get("default")
        if default is not None:
            return max(0.0, min(5.0, float(default))), actual, True, f"{field}={actual} (default)"
        return 0.0, actual, True, f"{field}={actual} 不在映射中"

    if method == "thresholds":
        value = _as_number(actual)
        if value is None:
            return None, actual, False, ""
        for rule in dim.get("thresholds", []):
            lower = _as_number(rule.get("min"))
            upper = _as_number(rule.get("max"))
            if lower is not None and value < lower:
                continue
            if upper is not None and value > upper:
                continue
            return max(0.0, min(5.0, float(rule.get("score", 0)))), actual, True, f"{field}={value}"
        default = dim.get("default")
        if default is not None:
            return max(0.0, min(5.0, float(default))), actual, True, f"{field}={value} (default)"
        return 0.0, actual, True, f"{field}={value} 未命中阈值"

    if method == "keyword":
        text = normalize_text(actual).lower()
        for rule in dim.get("rules", []):
            words = rule.get("any") or []
            if any(normalize_text(word).lower() in text for word in words if not is_missing(word)):
                return max(0.0, min(5.0, float(rule.get("score", 5)))), actual, True, rule.get("label") or f"命中 {words}"
        default = dim.get("default")
        if default is not None:
            return max(0.0, min(5.0, float(default))), actual, True, f"{field} 未命中关键词 (default)"
        return 0.0, actual, True, f"{field} 未命中关键词"

    if method == "minmax":
        value = _as_number(actual)
        if value is None or dim.get("id") not in minmax_stats:
            return None, actual, False, ""
        low, high = minmax_stats[dim.get("id")]
        if abs(high - low) < 1e-12:
            return 5.0, actual, True, f"{field}={value} (all equal)"
        if dim.get("direction") == "lower_better":
            score = 1.0 + 4.0 * (high - value) / (high - low)
        else:
            score = 1.0 + 4.0 * (value - low) / (high - low)
        note = f"{field}={value}"
        if candidate.get("price_anomaly") and not _condition_verified(candidate):
            score = min(score, 1.0)
            note += "；价格显著低于官方/自营锚点，价格分封顶 1.0（需先证实成色/发票/保修主体）"
        return max(0.0, min(5.0, score)), actual, True, note

    return None, actual, False, ""


def _minmax_stats(candidates: list[dict[str, Any]], dims: list[dict[str, Any]]) -> dict[str, tuple[float, float]]:
    stats: dict[str, tuple[float, float]] = {}
    for dim in dims:
        if dim.get("method") != "minmax":
            continue
        values = []
        for candidate in candidates:
            if not candidate.get("_hard_filter_eligible", True):
                continue
            value = _as_number(get_path(candidate, dim.get("field")))
            if value is not None:
                values.append(value)
        if values:
            stats[dim.get("id")] = (min(values), max(values))
    return stats


def score_candidates(
    candidates: list[dict[str, Any]],
    scorecard: dict[str, Any],
    brief: dict[str, Any] | None = None,
    *,
    assign_rank: bool = True,
) -> dict[str, Any]:
    brief = brief or {}
    errors, warnings = validate_scorecard(scorecard)
    if errors:
        raise ValueError("invalid scorecard: " + "; ".join(errors))

    dims = scorecard.get("dimensions", [])
    filters = list(scorecard.get("hard_filters", []))
    total_weight = sum(float(dim.get("weight", 0)) for dim in dims)

    # Brief-level exclusions are applied automatically.  They are collected
    # before scoring so an excluded variant never enters the minmax pool.
    exclusion_values = [
        normalize_text(value)
        for value in (brief.get("exclusions") or [])
        if normalize_text(value)
    ]
    if exclusion_values:
        filters.append(
            {
                "id": "brief_exclusions",
                "label": "需求排除项",
                "field": "filter_text",
                "op": "not_contains_any",
                "value": exclusion_values,
                "missing": "pass",
                "reason": "命中采购简报的排除项",
            }
        )

    # First pass: hard filters.  We keep a private flag for minmax stats.
    working: list[dict[str, Any]] = []
    for candidate in candidates:
        item = dict(candidate)
        if item.get("excluded_early"):
            item["_hard_filter_eligible"] = False
            item["_hard_filter_review"] = False
            item["_hard_filter_results"] = [
                {
                    "filter_id": "early_exclusion",
                    "label": "采集阶段排除",
                    "status": "fail",
                    "passed": False,
                    "actual": item.get("filter_text", ""),
                    "expected": None,
                    "reason": item.get("exclusion_reason") or "采集阶段命中排除项，已停止后续采集",
                }
            ]
            working.append(item)
            continue
        eligible, needs_review, filter_results = apply_hard_filters(item, filters, brief)
        item["_hard_filter_eligible"] = eligible
        item["_hard_filter_results"] = filter_results
        item["_hard_filter_review"] = needs_review
        working.append(item)

    staged = bool(scorecard.get("stages"))
    group_totals: dict[str, float] = {}
    if staged:
        for dim in dims:
            group = dim.get("group") or "fit"
            group_totals[group] = group_totals.get(group, 0.0) + float(dim.get("weight", 0) or 0)
    active_groups = len([total for total in group_totals.values() if total > 0]) or 1

    minmax_stats = _minmax_stats(working, dims)
    scored: list[dict[str, Any]] = []
    for item in working:
        breakdown: list[dict[str, Any]] = []
        weighted_points = 0.0
        evidence_weight = 0.0
        missing_dimensions: list[str] = []
        needs_review = bool(item.get("_hard_filter_review"))
        if item.get("price_anomaly") and not _condition_verified(item):
            needs_review = True

        for dim in dims:
            dim_id = dim.get("id")
            weight = float(dim.get("weight", 0))
            if staged:
                group = dim.get("group") or "fit"
                group_total = group_totals.get(group) or 1.0
                weight = (weight / group_total) / active_groups
            score, raw, known, note = _score_dimension(item, dim, minmax_stats)
            if score is None:
                policy = dim.get("missing", "worst")
                if policy == "neutral":
                    score = 2.5
                else:
                    score = 0.0
                if policy == "review":
                    needs_review = True
                missing_dimensions.append(dim_id)
            else:
                evidence_weight += weight
            points = (score / 5.0) * weight * 100.0
            weighted_points += points
            breakdown.append(
                {
                    "dimension_id": dim_id,
                    "label": dim.get("label") or dim_id,
                    "weight": weight,
                    "raw_value": raw,
                    "normalized_score": round(score, 3),
                    "weighted_points": round(points, 3),
                    "known": known,
                    "evidence": note,
                    "source": dim.get("field") or "manual",
                }
            )

        evidence_ratio = evidence_weight / total_weight if total_weight else 0.0
        base_confidence = float(item.get("confidence", 0.5) or 0.5)
        score_confidence = round(base_confidence * (0.5 + 0.5 * evidence_ratio), 2)
        low_confidence = score_confidence < 0.6 or evidence_ratio < 0.7
        item["score"] = round(weighted_points, 2)
        item["score_breakdown"] = breakdown
        item["evidence_ratio"] = round(evidence_ratio, 2)
        item["score_confidence"] = score_confidence
        item["low_confidence"] = low_confidence
        item["missing_dimensions"] = missing_dimensions
        missing_fields: list[str] = []
        if item.get("price_status") != "visible":
            missing_fields.append("price")
        for field, label in (
            ("specs", "specs"),
            ("warranty", "warranty"),
            ("invoice", "invoice"),
            ("stock_status", "stock"),
        ):
            if is_missing(get_path(item, f"detail.{field}")):
                missing_fields.append(label)
        if is_missing(item.get("sales")):
            missing_fields.append("sales")
        if is_missing(item.get("shop_name")):
            missing_fields.append("shop")
        item["missing_fields"] = missing_fields
        item["eligible"] = bool(item.pop("_hard_filter_eligible"))
        item["hard_filter_results"] = item.pop("_hard_filter_results")
        item.pop("_hard_filter_review", None)
        item["elimination_reasons"] = [
            (
                f"{result['label']}：{result['reason']}"
                if result.get("label") and result.get("label") not in result.get("reason", "")
                else result["reason"]
            )
            for result in item["hard_filter_results"]
            if result["status"] == "fail"
        ]
        item["needs_review"] = bool(item.get("needs_review")) or needs_review or low_confidence
        item["scorecard_id"] = scorecard.get("id") or scorecard.get("name")
        item["scorecard_version"] = scorecard.get("version", "1.0")
        scored.append(item)

    eligible_items = [item for item in scored if item.get("eligible")]
    eligible_items.sort(
        key=lambda item: (
            -float(item.get("score", 0)),
            -float(item.get("score_confidence", 0)),
            float((item.get("landed_price") or {}).get("floor") or item.get("price") or float("inf")),
        )
    )
    if assign_rank:
        for rank, item in enumerate(eligible_items, start=1):
            item["rank"] = rank
        for item in scored:
            if not item.get("eligible"):
                item["rank"] = None
    else:
        for item in scored:
            item["rank"] = None

    summary = {
        "total": len(scored),
        "eligible": len(eligible_items),
        "eliminated": len(scored) - len(eligible_items),
        "needs_review": sum(1 for item in scored if item.get("needs_review")),
        "low_confidence": sum(1 for item in scored if item.get("low_confidence")),
        "top_score": eligible_items[0].get("score") if eligible_items else None,
        "scorecard": scorecard.get("name"),
        "weights_sum": round(total_weight, 6),
    }
    return {
        "candidates": scored,
        "scorecard": scorecard,
        "summary": summary,
        "warnings": warnings,
        "errors": [],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Apply hard filters and a weighted scorecard")
    parser.add_argument("--candidates", required=True, help="candidates with landed/TCO data")
    parser.add_argument("--scorecard", required=True)
    parser.add_argument("--brief", default=None)
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)

    payload = load_json(args.candidates)
    candidates = payload.get("candidates", payload) if isinstance(payload, dict) else payload
    scorecard = load_json(args.scorecard)
    brief = load_json(args.brief) if args.brief else {}
    result = score_candidates(candidates, scorecard, brief)
    save_json(args.output, result)
    print(
        f"scored {result['summary']['total']} candidates, eligible={result['summary']['eligible']}, "
        f"needs_review={result['summary']['needs_review']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
