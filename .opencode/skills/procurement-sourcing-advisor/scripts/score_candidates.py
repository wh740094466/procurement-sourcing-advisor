"""Apply hard filters and an auditable, AI-planned scorecard.

The scorecard is generated by the agent for the actual item, but it is ordinary
JSON with explicit dimensions, weights, evidence paths, and missing-data
policies.  This script does the arithmetic deterministically so a fluent
recommendation cannot hide a missing field or an unstated weight.
"""

